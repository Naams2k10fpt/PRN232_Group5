-- One-time bridge for databases that already ran the two TV3 chat migrations
-- before main introduced AddStudyGroupChat. Back up the database first.
-- This preserves rooms, members, messages, requests, invitations and IDs.
-- Do not run on a fresh database or one already on the main chat schema.
BEGIN;

DO $check$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM "__EFMigrationsHistory"
                   WHERE "MigrationId" = '20261001090000_AddStudyGroups')
       OR NOT EXISTS (SELECT 1 FROM "__EFMigrationsHistory"
                      WHERE "MigrationId" = '20261004090016_AddStudyGroupAccess')
       OR EXISTS (SELECT 1 FROM "__EFMigrationsHistory"
                  WHERE "MigrationId" = '20261004090814_AddStudyGroupChat') THEN
        RAISE EXCEPTION 'Expected legacy TV3 chat schema, not the current migration history';
    END IF;
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_name = 'StudyGroupMembers' AND column_name = 'Id') THEN
        RAISE EXCEPTION 'StudyGroupMembers already has the main schema key';
    END IF;
END
$check$;

-- Main uses a surrogate member key and retains the unique room/user pair.
ALTER TABLE "StudyGroupMembers" ADD COLUMN "Id" integer GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE "StudyGroupMembers" DROP CONSTRAINT "PK_StudyGroupMembers";
ALTER TABLE "StudyGroupMembers" ADD CONSTRAINT "PK_StudyGroupMembers" PRIMARY KEY ("Id");
CREATE UNIQUE INDEX "IX_StudyGroupMembers_GroupId_UserId"
    ON "StudyGroupMembers" ("GroupId", "UserId");

-- Align the shared chat tables with main's mappings while keeping TV3 fields.
ALTER TABLE "GroupMessages" ALTER COLUMN "Content" TYPE text;
DROP INDEX "IX_GroupMessages_GroupId_Id";
CREATE INDEX "IX_GroupMessages_GroupId_SentAt" ON "GroupMessages" ("GroupId", "SentAt");

ALTER TABLE "StudyGroups" RENAME CONSTRAINT "FK_StudyGroups_Subjects_SubjectId" TO "FK_StudyGroups_Subjects";
ALTER TABLE "StudyGroups" RENAME CONSTRAINT "FK_StudyGroups_Users_CreatedByUserId" TO "FK_StudyGroups_Users";
ALTER TABLE "StudyGroupMembers" RENAME CONSTRAINT "FK_StudyGroupMembers_StudyGroups_GroupId" TO "FK_StudyGroupMembers_Groups";
ALTER TABLE "StudyGroupMembers" DROP CONSTRAINT "FK_StudyGroupMembers_Users_UserId";
ALTER TABLE "StudyGroupMembers" ADD CONSTRAINT "FK_StudyGroupMembers_Users"
    FOREIGN KEY ("UserId") REFERENCES "Users" ("Id") ON DELETE RESTRICT;
ALTER TABLE "GroupMessages" RENAME CONSTRAINT "FK_GroupMessages_StudyGroups_GroupId" TO "FK_GroupMessages_Groups";
ALTER TABLE "GroupMessages" RENAME CONSTRAINT "FK_GroupMessages_Users_SenderUserId" TO "FK_GroupMessages_Users";

DELETE FROM "__EFMigrationsHistory"
WHERE "MigrationId" IN ('20261001090000_AddStudyGroups', '20261004090016_AddStudyGroupAccess');
INSERT INTO "__EFMigrationsHistory" ("MigrationId", "ProductVersion") VALUES
    ('20261004090814_AddStudyGroupChat', '9.0.20'),
    ('20261004150401_AddStudyGroupAccessAfterChat', '9.0.20');

COMMIT;
